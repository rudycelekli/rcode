/** Embed builtin/ (commands, agents, skills) into a generated module so compiled binaries carry it. */
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
const root = join(import.meta.dir, "..", "builtin");
const files: Record<string, string> = {};
const walk = (d: string) => { for (const e of readdirSync(d)) { const p = join(d, e); statSync(p).isDirectory() ? walk(p) : (files[relative(root, p)] = readFileSync(p, "utf8")); } };
walk(root);
writeFileSync(join(import.meta.dir, "..", "src", "ext", "builtin-data.generated.ts"), `// Generated by scripts/gen-builtin.ts — do not edit.\nexport const BUILTIN_FILES: Record<string, string> = ${JSON.stringify(files)};\n`);
console.log(`embedded ${Object.keys(files).length} builtin files`);
